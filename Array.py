# Contoh operasi dasar pada list.

# Menyisipkan data pada indeks tertentu.
buku = ["Python", "PHP", "C++"]
buku.insert(2, "Cloud Computing")
print(buku)

# Mengubah data pada indeks pertama.
buku = ["Python", "PHP", "C++"]
buku[0] = "Pemrograman Python"
print(buku)

# Menambahkan data di akhir list.
buku = ["Python", "PHP", "C++"]
buku.append("Jaringan Komputer")
print(buku)

# Menghapus data berdasarkan nilainya.
buku = ["Python", "PHP", "C++"]
buku.remove("PHP")
print(buku)
